package se.uulm.snowballr.backend.openapi

import kotlinx.serialization.ExperimentalSerializationApi
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Tag
import org.junit.jupiter.api.Test
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.test.context.SpringBootTest
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc
import org.springframework.test.web.servlet.MockMvc
import org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get
import org.springframework.test.web.servlet.result.MockMvcResultMatchers.status
import se.uulm.snowballr.backend.openapi.OpenApiContractTest.Companion.BUILD_SPEC
import se.uulm.snowballr.backend.openapi.OpenApiContractTest.Companion.COMMITTED_SPEC
import se.uulm.snowballr.backend.rest.SnowballRApplication
import java.io.File

/**
 * Emits the code-first OpenAPI specification on build and guards it against drift.
 *
 * The specification is generated by springdoc from the REST controllers and served at the configured
 * `springdoc.api-docs.path`. This test fetches it, writes the canonical form to [BUILD_SPEC] (the build
 * artifact consumed by the OpenAPI TypeScript client generator), and asserts it matches the committed
 * [COMMITTED_SPEC]. Whenever the REST surface changes, the committed copy must be regenerated and committed.
 *
 * The full application context is deliberately pinned to [SnowballRApplication], whose component scan is
 * confined to the `rest` package, so the context is cheap to start and requires no database or Koin wiring.
 */
@SpringBootTest(classes = [SnowballRApplication::class])
@AutoConfigureMockMvc
@Tag("openapi")
class OpenApiContractTest(@Autowired private val mvc: MockMvc) {
    @Test
    fun `When the REST surface is unchanged, then the generated OpenAPI spec matches the committed one`() {
        val generated = canonicalize(fetchOpenApiSpec())

        val buildSpec = File(BUILD_SPEC)
        buildSpec.parentFile.mkdirs()
        buildSpec.writeText(generated)

        val committed = File(COMMITTED_SPEC)
        assertTrue(committed.exists()) {
            "$COMMITTED_SPEC is missing. Run `cp $BUILD_SPEC $COMMITTED_SPEC` and commit it."
        }
        assertEquals(committed.readText(), generated) {
            "The OpenAPI spec is out of date. Run `cp $BUILD_SPEC $COMMITTED_SPEC` and commit the result."
        }
    }

    /**
     * Fetches the OpenAPI specification from the springdoc endpoint.
     */
    private fun fetchOpenApiSpec(): String = mvc.perform(get(API_DOCS_PATH))
        .andExpect(status().isOk)
        .andReturn()
        .response
        .getContentAsString(Charsets.UTF_8)

    /**
     * Normalizes the specification into a stable, diff-friendly form: object keys are sorted recursively and
     * the result is pretty-printed with a fixed indentation, independent of springdoc's internal ordering.
     */
    private fun canonicalize(raw: String): String =
        JSON.encodeToString(JsonElement.serializer(), JSON.parseToJsonElement(raw)) + "\n"

    private companion object {
        /** Path the springdoc api-docs endpoint is served at (see `application.properties`). */
        const val API_DOCS_PATH = "/api"

        /** Build artifact consumed by the OpenAPI TypeScript client generator. */
        const val BUILD_SPEC = "build/openapi.json"

        /** Committed specification the build is checked against. */
        const val COMMITTED_SPEC = "api/openapi.json"

        @OptIn(ExperimentalSerializationApi::class)
        val JSON: Json = Json {
            prettyPrint = true
            prettyPrintIndent = "    "
        }
    }
}
